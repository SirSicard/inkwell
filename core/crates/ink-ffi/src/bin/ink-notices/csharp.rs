//! The generated C# for the Windows shell: `static partial class RustNotices`, one
//! `RustCrateNotice` per crate (the record is hand-written in
//! `windows/Inkwell.Core/Screens/About/Notices.cs`), and the fingerprint of the lock it was
//! generated from. The same crates' notices as the Swift file's ([`crate::swift`]), for the
//! Windows target.

use std::fmt::Write as _;

use crate::swift::{CrateNotice, string};

/// The value of `public const string <name> = "...";` in generated C#.
pub fn recorded(csharp: &str, name: &str) -> Option<String> {
    let prefix = format!("public const string {name} = \"");
    csharp.lines().find_map(|line| {
        let rest = line.trim_start().strip_prefix(&prefix)?;
        rest.strip_suffix("\";").map(str::to_string)
    })
}

/// The number of `"` a raw string literal needs so that `text` cannot close it: one more than the
/// longest run of quotes in it, and at least three.
fn raw_quotes(text: &str) -> usize {
    let (mut longest, mut run) = (0, 0);
    for c in text.chars() {
        run = if c == '"' { run + 1 } else { 0 };
        longest = longest.max(run);
    }
    (longest + 1).max(3)
}

/// The C# file. `crates` must already be sorted.
pub fn render(features: &str, target: &str, fingerprint: &str, crates: &[CrateNotice]) -> String {
    let mut out = String::new();
    out.push_str(
        "// <auto-generated>\n\
         // Generated by `cargo run -p ink-ffi --bin ink-notices -- --windows`: do not edit. Regenerate\n\
         // after any change to core/Cargo.lock, a crate's manifest or core/crates/ink-ffi/notices/ (the\n\
         // core's tests and RustNoticesTests fail while this file was made from another Cargo.lock;\n\
         // `ink-notices --windows --check` fails on any difference).\n\
         // </auto-generated>\n\
         //\n\
         // The licence notices of the third-party Rust crates linked into the core (ink_ffi.dll) as the\n\
         // Windows release builds it: ink-ffi's normal dependencies for the target and features below.\n\
         // Build scripts, proc macros, dev-only crates and the workspace's own crates are not in the app\n\
         // and are left out; C and C++ code a crate compiles in (llama.cpp, SQLite) has its own notice in\n\
         // Notices.cs. The texts are the crates' own licence files, with line ends normalised and\n\
         // trailing spaces trimmed; core/crates/ink-ffi/src/bin/ink-notices says which files ship.\n\
         \n\
         namespace Inkwell.Core.Screens;\n\
         \n\
         public static partial class RustNotices\n\
         {\n",
    );
    let _ = writeln!(
        out,
        "    /// <summary>The cargo features the release builds the core with.</summary>"
    );
    let _ = writeln!(
        out,
        "    public const string Features = {};",
        string(features)
    );
    let _ = writeln!(
        out,
        "    /// <summary>The target the release builds the core for.</summary>"
    );
    let _ = writeln!(out, "    public const string Target = {};", string(target));
    let _ = writeln!(
        out,
        "    /// <summary>FNV-1a (64-bit) of the features, a line feed, the target, a line feed and\n    \
         /// core/Cargo.lock (line ends normalised) this was generated from.</summary>"
    );
    let _ = writeln!(
        out,
        "    public const string LockFingerprint = {};",
        string(fingerprint)
    );
    out.push('\n');
    let _ = writeln!(
        out,
        "    /// <summary>Every crate, in name order.</summary>"
    );
    let _ = writeln!(
        out,
        "    public static IReadOnlyList<RustCrateNotice> Crates {{ get; }} ="
    );
    let _ = writeln!(out, "    [");
    for c in crates {
        let quotes = "\"".repeat(raw_quotes(&c.text));
        let _ = writeln!(
            out,
            "        new({}, {}, {}, {}, {quotes}\n{}\n{quotes}),",
            string(&c.name),
            string(&c.version),
            string(&c.licence),
            string(&c.shown),
            c.text
        );
    }
    out.push_str("    ];\n}\n");
    out
}

/// The crates a generated file lists, as `name version`: the header line of each `new(`, read
/// outside the licence texts (a raw literal from its opening line, which ends in its quotes, to
/// its closing one, the same quotes and `),`), so no text can add or hide a crate.
pub fn listed(csharp: &str) -> Vec<String> {
    let mut out = Vec::new();
    let mut closing: Option<String> = None;
    for line in csharp.lines() {
        if let Some(end) = &closing {
            if line == end {
                closing = None;
            }
            continue;
        }
        let Some(rest) = line.strip_prefix("        new(\"") else {
            continue;
        };
        let quotes = line.len() - line.trim_end_matches('"').len();
        if quotes < 3 {
            continue;
        }
        closing = Some(format!("{}),", "\"".repeat(quotes)));
        if let Some((name, rest)) = rest.split_once('"')
            && let Some(version) = rest.strip_prefix(", \"").and_then(|r| r.split('"').next())
        {
            out.push(format!("{name} {version}"));
        }
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    fn notice(name: &str, text: &str) -> CrateNotice {
        CrateNotice {
            name: name.into(),
            version: "1.0.0".into(),
            licence: "MIT OR Apache-2.0".into(),
            shown: "MIT".into(),
            text: text.into(),
        }
    }

    #[test]
    fn the_raw_literal_outgrows_any_run_of_quotes_in_its_text() {
        assert_eq!(raw_quotes("no quotes"), 3);
        assert_eq!(raw_quotes("\"AS IS\" and \"\""), 3);
        assert_eq!(raw_quotes("ends a literal \"\"\" here"), 4);
        assert_eq!(raw_quotes("\"\"\"\"\" five"), 6);
        let cs = render("f", "t", "0123456789abcdef", &[notice("a", "x \"\"\" y")]);
        assert!(
            cs.contains("        new(\"a\", \"1.0.0\", \"MIT OR Apache-2.0\", \"MIT\", \"\"\"\"\nx \"\"\" y\n\"\"\"\"),"),
            "{cs}"
        );
    }

    #[test]
    fn the_csharp_records_what_it_was_made_from_and_lists_the_crates_in_order() {
        let cs = render(
            "engine-a,b/c",
            "x86_64-pc-windows-msvc",
            "0123456789abcdef",
            &[notice("a", "A"), notice("b", "B")],
        );
        assert_eq!(recorded(&cs, "Features").as_deref(), Some("engine-a,b/c"));
        assert_eq!(
            recorded(&cs, "Target").as_deref(),
            Some("x86_64-pc-windows-msvc")
        );
        assert_eq!(
            recorded(&cs, "LockFingerprint").as_deref(),
            Some("0123456789abcdef")
        );
        assert_eq!(listed(&cs), ["a 1.0.0", "b 1.0.0"]);
        assert!(cs.starts_with("// <auto-generated>\n"), "analyzers skip it");
        assert!(cs.contains("namespace Inkwell.Core.Screens;\n"));
        assert!(cs.ends_with("    ];\n}\n"));
        assert_eq!(
            cs,
            render(
                "engine-a,b/c",
                "x86_64-pc-windows-msvc",
                "0123456789abcdef",
                &[notice("a", "A"), notice("b", "B")]
            ),
            "deterministic"
        );
    }

    #[test]
    fn listed_reads_only_the_crate_headers_never_a_licence_text() {
        let tricky = "        new(\"fake\", \"9.9.9\", \"MIT\", \"MIT\", \"\"\"";
        let cs = render(
            "f",
            "t",
            "0123456789abcdef",
            &[
                notice("real", &format!("a text quoting a header:\n{tricky}\nmore")),
                notice("second", "B"),
            ],
        );
        assert!(cs.contains("new(\"fake\""), "the trap is in the file");
        assert_eq!(listed(&cs), ["real 1.0.0", "second 1.0.0"]);
    }
}
